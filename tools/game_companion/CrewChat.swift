import SwiftUI
import AppKit

// The crew chat: ONE read-only timeline of the room thread (issue 15) and the Hotline (pull request 35), newest at the bottom, with name tags
// and colours. Only the owner's account is read (that is who posts for everyone, tagged in the text). Technical noise (Switchboard start/result/relay
// lines, "(mirror of ...)" duplicates, bot footers) is hidden behind ONE switch that is off by default.
// Honest by construction: while it loads it says so; if a read fails the list is EMPTY and says "Couldn't load the room (as of <time>)". An old list is never shown as current.

enum CrewChatData {
 static let hotlinePR = 35

 // Newest 200 comments of one issue or pull request thread, tagged with where they came from. Nil means the read failed.
 static func fetch(issue: Int,source: String,token: String?) async -> [RoomMessage]? {
  guard let first = MeetingData.api("/issues/\(issue)/comments?per_page=100",token:token) else { return nil }
  guard let (data,response) = try? await URLSession.shared.data(for:first),
        (response as? HTTPURLResponse)?.statusCode == 200, var all = MeetingData.parseMessages(data) else { return nil }
  if let link = (response as? HTTPURLResponse)?.value(forHTTPHeaderField:"Link"), let last = MeetingData.lastPage(link), last > 1 {
   var more: [RoomMessage] = []
   for page in (last > 2 ? [last - 1,last] : [last]) {
    guard let request = MeetingData.api("/issues/\(issue)/comments?per_page=100&page=\(page)",token:token),
          let (d,resp) = try? await URLSession.shared.data(for:request), (resp as? HTTPURLResponse)?.statusCode == 200,
          let got = MeetingData.parseMessages(d) else { return nil }   // a missing page would leave a hole: treat as a failed read
    more += got
   }
   all = more
  }
  for i in all.indices { all[i].source = source }
  return all
 }

 // Technical lines most people don't want in a chat.
 static func isNoise(_ message: RoomMessage) -> Bool {
  let text = message.text.trimmingCharacters(in:.whitespacesAndNewlines)
  let low = text.lowercased()
  if text.isEmpty { return true }
  if low.contains("(mirror of") || low.hasPrefix("mirror of") { return true }
  if low.contains("generated by claude code") || low.contains("generated by [claude code]") { return true }
  if low.hasPrefix("switchboard") || low.hasPrefix("[switchboard") || low.hasPrefix("🔌") { return true }
  if low.contains("switchboard") && (low.contains("switchboard start") || low.contains("switchboard result") || low.contains("switchboard relay")) { return true }
  return false
 }
}

@MainActor final class CrewChatHub: ObservableObject {
 enum Status { case idle, loading, loaded(Date), failed(Date) }
 @Published var status = Status.idle
 @Published var messages: [RoomMessage] = []
 @Published var showTechnical = false
 @Published var expanded: Set<Int> = []
 private var lastRun = Date.distantPast

 var shown: [RoomMessage] { showTechnical ? messages : messages.filter { !CrewChatData.isNoise($0) } }

 func refresh(token: String?,force: Bool = false) async {
  if case .loading = status { return }
  if !force && Date().timeIntervalSince(lastRun) < 300 { return }   // keyless GitHub reads are limited (60 an hour per network): about 4 reads a refresh, so no more than once in 5 minutes unless Refresh is pressed
  guard !GuardHub.isOffline else { messages = []; status = .failed(Date()); return }
  status = .loading
  lastRun = Date()
  // Test copies only: `defaults write ... test.failChat -bool true` forces a failed read so the failure screen can be checked.
  let forced = UserDefaults.standard.bool(forKey:"test.failChat")
  async let room = CrewChatData.fetch(issue:MeetingData.issue,source:"",token:token)
  async let hotline = CrewChatData.fetch(issue:CrewChatData.hotlinePR,source:"hotline",token:token)
  var (a,b) = await (room,hotline)
  // A saved key that GitHub no longer accepts (401) must not hide a public thread: retry the failed read without it, like the Meeting Room does.
  if token != nil {
   if a == nil { a = await CrewChatData.fetch(issue:MeetingData.issue,source:"",token:nil) }
   if b == nil { b = await CrewChatData.fetch(issue:CrewChatData.hotlinePR,source:"hotline",token:nil) }
  }
  if let a = a, let b = b, !forced {
   messages = (a + b).sorted { ($0.date ?? .distantPast) < ($1.date ?? .distantPast) }
   status = .loaded(Date())
  } else {
   messages = []      // never keep an old list on screen as if it were current
   status = .failed(Date())
  }
 }
}

extension CompanionInterfaceView {
 func crewChatTime(_ date: Date) -> String {
  let f = DateFormatter()
  f.timeZone = TimeZone(identifier:"America/Moncton") ?? .current
  f.dateFormat = Calendar.current.isDateInToday(date) ? "h:mm a" : "MMM d, h:mm a"
  return f.string(from:date)
 }

 // The Messages tab's main view: the group chat. Read-only: there is no writing box here.
 var crewChatPage: some View {
  let list = meeting.chat.shown
  return VStack(alignment:.leading,spacing:10) {
   HStack(spacing:12) {
    VStack(alignment:.leading,spacing:2) {
     Text("Crew chat").font(.system(size:20,weight:.bold,design:.rounded)).foregroundStyle(HubTheme.text)
     Text(crewChatStatusLine).font(.system(size:12)).foregroundStyle(HubTheme.subtext)
    }
    Spacer(minLength:8)
    Toggle("Show technical lines",isOn:Binding(get:{ meeting.chat.showTechnical },set:{ meeting.chat.showTechnical = $0 })).toggleStyle(.switch).font(.system(size:12)).foregroundStyle(HubTheme.subtext)
     .accessibilityHint("Shows Switchboard lines, mirrored copies and bot footers")
   }
   switch meeting.chat.status {
   case .failed:
    Text("Couldn't load the room. Tap Refresh to try again.").font(.system(size:15)).foregroundStyle(HubTheme.amber).padding(.vertical,30).frame(maxWidth:.infinity)
   case .idle,.loading:
    if list.isEmpty { Text("Loading…").font(.system(size:15)).foregroundStyle(HubTheme.subtext).padding(.vertical,30).frame(maxWidth:.infinity) }
    else { crewChatList(list) }
   case .loaded:
    if list.isEmpty { Text("Nothing in the chat yet.").font(.system(size:15)).foregroundStyle(HubTheme.subtext).padding(.vertical,30).frame(maxWidth:.infinity) }
    else { crewChatList(list) }
   }
  }
  .onAppear { Task { await meeting.chat.refresh(token:meeting.hasToken ? meeting.savedToken() : nil) } }
 }

 var crewChatStatusLine: String {
  switch meeting.chat.status {
  case .idle: return "Not loaded yet"
  case .loading: return "Loading…"
  case .loaded(let at): return "The room + the Hotline · as of \(crewChatTime(at)) · newest at the bottom"
  case .failed(let at): return "Couldn't load the room (as of \(crewChatTime(at)))"
  }
 }

 func crewChatList(_ list: [RoomMessage]) -> some View {
  ScrollViewReader { proxy in
   ScrollView {
    LazyVStack(alignment:.leading,spacing:10) {
     ForEach(list.suffix(150)) { message in crewChatRow(message).id(message.id) }
     Color.clear.frame(height:1).id("bottom")
    }
    .padding(.vertical,4)
   }
   .scrollIndicators(.hidden)
   .onAppear { proxy.scrollTo("bottom",anchor:.bottom) }
   .onChange(of:list.count) { _,_ in proxy.scrollTo("bottom",anchor:.bottom) }
  }
 }

 func crewChatRow(_ message: RoomMessage) -> some View {
  let open = meeting.chat.expanded.contains(message.id)
  let tint = hubOwnerTint(message.author)
  return VStack(alignment:.leading,spacing:5) {
   HStack(spacing:8) {
    Text(MeetingData.speaker(message.author)).font(.system(size:12.5,weight:.bold,design:.rounded)).foregroundStyle(tint)
    if !message.to.isEmpty { Text("→ \(MeetingData.speaker(message.to))").font(.system(size:12,design:.rounded)).foregroundStyle(HubTheme.subtext) }
    if message.source == "hotline" {
     Text("Hotline").font(.system(size:10.5,weight:.semibold,design:.monospaced)).foregroundStyle(HubTheme.teal)
      .padding(.horizontal,6).padding(.vertical,1).overlay(RoundedRectangle(cornerRadius:4).stroke(HubTheme.teal.opacity(0.6),lineWidth:1))
    }
    Text(message.date.map { crewChatTime($0) } ?? "").font(.system(size:11.5)).foregroundStyle(HubTheme.subtext)
    Spacer(minLength:0)
   }
   Text(open ? message.text : MeetingData.brief(message.text,limit:320)).font(.system(size:14)).foregroundStyle(HubTheme.text)
    .fixedSize(horizontal:false,vertical:true).textSelection(.enabled)
  }
  .padding(12).frame(maxWidth:.infinity,alignment:.leading)
  .background(HubTheme.card,in:RoundedRectangle(cornerRadius:12))
  .overlay(alignment:.leading) { Rectangle().fill(tint).frame(width:3).clipShape(RoundedRectangle(cornerRadius:2)) }
  .contentShape(Rectangle())
  .onTapGesture { if MeetingData.isCut(message.text,limit:320) { if open { meeting.chat.expanded.remove(message.id) } else { meeting.chat.expanded.insert(message.id) } } }
  .accessibilityElement(children:.combine)
 }
}

